export function researchNarrative(kind, research, project) {
  const cards = SCENES[kind];
  if (!cards) return '';
  const signature = `${kind}:${project?.id}:${project?.type}:${project?.runs}:${project?.reviews}:${research?.rngState}`;
  let hash = 2166136261;
  for (const char of signature) hash = Math.imul(hash ^ char.codePointAt(0), 16777619) >>> 0;
  return cards[hash % cards.length];
}
